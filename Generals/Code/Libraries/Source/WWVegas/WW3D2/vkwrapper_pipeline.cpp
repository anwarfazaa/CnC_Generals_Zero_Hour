VkFormat VkWrapper::FindDepthFormat()
{
    return FindSupportedFormat(
        {VK_FORMAT_D32_SFLOAT, VK_FORMAT_D32_SFLOAT_S8_UINT, VK_FORMAT_D24_UNORM_S8_UINT},
        VK_IMAGE_TILING_OPTIMAL,
        VK_FORMAT_FEATURE_DEPTH_STENCIL_ATTACHMENT_BIT
    );
}

VkFormat VkWrapper::FindSupportedFormat(const std::vector<VkFormat>& candidates,
                                       VkImageTiling tiling,
                                       VkFormatFeatureFlags features)
{
    for (VkFormat format : candidates) {
        VkFormatProperties props;
        vkGetPhysicalDeviceFormatProperties(context.physical_device, format, &props);

        if (tiling == VK_IMAGE_TILING_LINEAR && (props.linearTilingFeatures & features) == features) {
            return format;
        } else if (tiling == VK_IMAGE_TILING_OPTIMAL && (props.optimalTilingFeatures & features) == features) {
            return format;
        }
    }

    return VK_FORMAT_UNDEFINED;
}

uint64_t VkWrapper::ComputePipelineHash()
{
    // Simple hash based on current state
    // In production, this would hash all relevant pipeline state
    uint64_t hash = 0;
    hash ^= (uint64_t)fog_enabled;
    hash ^= ((uint64_t)current_light_enables[0] << 1);
    return hash;
}

VulkanPipeline* VkWrapper::GetOrCreatePipeline()
{
    uint64_t hash = ComputePipelineHash();

    auto it = pipeline_cache.find(hash);
    if (it != pipeline_cache.end()) {
        return it->second;
    }

    // For now, just return the default pipeline
    // Full implementation would create new pipeline based on state
    return current_pipeline;
}
